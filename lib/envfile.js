'use strict';
function parseEnv(text = '') {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}
function buildEnv(v) {
  return `# Generated by "npm run setup". Never share this file or post screenshots of it.
BOT_TOKEN=${v.BOT_TOKEN}
DB_HOST=${v.DB_HOST}
DB_PORT=${v.DB_PORT}
DB_USER=${v.DB_USER}
DB_PASSWORD=${v.DB_PASSWORD}
DB_NAME=${v.DB_NAME}
PORT=${v.PORT || 3000}
TZ_NAME=${v.TZ_NAME || 'Asia/Phnom_Penh'}
NOTIFY_CHAT_ID=${v.NOTIFY_CHAT_ID}
MENTIONS=${v.MENTIONS}
CONTACT_NAME=${v.CONTACT_NAME}
AUTO_NOTIFY=${v.AUTO_NOTIFY || 'true'}
SELF_REGISTER=${v.SELF_REGISTER || 'true'}
`;
}
const extractTunnelUrl = (line) => (String(line).match(/https:\/\/[a-z0-9-]+\.trycloudflare\.com/i) || [])[0] || null;
module.exports = { parseEnv, buildEnv, extractTunnelUrl };
